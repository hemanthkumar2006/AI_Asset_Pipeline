def generate_dummy_texture(output_dir: str, size: int = 256) -> str:
    """Generate a checkerboard texture PNG using Pillow (with stdlib fallback)."""
    texture_path = os.path.join(output_dir, "texture.png")

    try:
        from PIL import Image

        img = Image.new("RGB", (size, size), color=(100, 149, 237))
        pixels = img.load()
        for y in range(size):
            for x in range(size):
                if (x // 32 + y // 32) % 2 == 0:
                    pixels[x, y] = (100, 149, 237)   # Cornflower blue
                else:
                    pixels[x, y] = (70, 130, 180)     # Steel blue

        img.save(texture_path)
        report_log("Texture generated with Pillow")
        return texture_path

    except ImportError:
        # Fallback: build a minimal valid PNG without any third-party library
        report_log("Pillow not installed - creating minimal PNG via stdlib")

        import struct
        import zlib

        width, height = 4, 4
        raw_data = b""
        for y in range(height):
            raw_data += b"\x00"  # PNG filter byte (None)
            for x in range(width):
                if (x + y) % 2 == 0:
                    raw_data += bytes([100, 149, 237])
                else:
                    raw_data += bytes([70, 130, 180])

        def _make_chunk(chunk_type: bytes, data: bytes) -> bytes:
            crc = zlib.crc32(chunk_type + data) & 0xFFFFFFFF
            return struct.pack(">I", len(data)) + chunk_type + data + struct.pack(">I", crc)

        ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
        compressed = zlib.compress(raw_data)

        with open(texture_path, "wb") as f:
            f.write(b"\x89PNG\r\n\x1a\n")
            f.write(_make_chunk(b"IHDR", ihdr))
            f.write(_make_chunk(b"IDAT", compressed))
            f.write(_make_chunk(b"IEND", b""))

        return texture_path


