def main() -> None:
    parser = argparse.ArgumentParser(
        description="AI 3D Asset Pipeline - Python Backend",
    )
    parser.add_argument(
        "--video_path", type=str, required=True,
        help="Path to the input video file",
    )
    parser.add_argument(
        "--output_dir", type=str, required=True,
        help="Directory to save generated assets",
    )
    parser.add_argument(
        "--click_x", type=float, default=0.5,
        help="Normalised X coordinate of user click (0.0-1.0)",
    )
    parser.add_argument(
        "--click_y", type=float, default=0.5,
        help="Normalised Y coordinate of user click (0.0-1.0)",
    )

    args = parser.parse_args()

    if not os.path.exists(args.video_path):
        report_error(f"Video file not found: {args.video_path}")
        sys.exit(1)

    try:
        run_dummy_pipeline(args.video_path, args.output_dir)
    except Exception as exc:
        report_error(f"Pipeline failed: {exc}")
        sys.exit(1)


if __name__ == "__main__":
    main()
